#!/bin/bash
# Export every Claude Code conversation on this machine to readable Markdown in context/chats/: what the user and
# Claude said, in order, and one line per tool call (outputs are left out). A new session, or a person, can read the
# whole history from the repo even if the session that produced it is gone. Called by snapshot.sh. Needs jq.
set -u
REPO="$HOME/monster"
OUT="$REPO/context/chats"
mkdir -p "$OUT"
command -v jq >/dev/null || { echo "export_context: jq is missing"; exit 0; }

JQ='def hm: (.timestamp // "")[11:16];
select((.type == "user" or .type == "assistant") and (.isMeta != true))   # isMeta: injected skill text, command caveats
| . as $m
| ($m.message.content | if type == "string" then [{type: "text", text: .}] else (. // []) end)[]
| if .type == "text" and ((.text | length) > 0) and ((.text | startswith("<system-reminder>")) | not) then
    "### \($m | hm) \($m.type)\n\n\(.text)\n"
  elif .type == "tool_use" then
    "- `\($m | hm)` **\(.name)** \((.input.command // .input.file_path // .input.query // .input.url // .input.description // .input.skill // "") | tostring | gsub("\n"; " ⏎ ") | .[0:400])"
  else empty end'

for f in "$HOME"/.claude/projects/*/*.jsonl; do
  [ -f "$f" ] || continue
  sid=$(basename "$f" .jsonl)
  first=$(jq -r 'select(.timestamp) | .timestamp' "$f" 2>/dev/null | head -1)
  [ -n "$first" ] || continue
  dst="$OUT/${first:0:10}_${first:11:2}${first:14:2}_${sid:0:8}.md"
  [ -f "$dst" ] && [ "$dst" -nt "$f" ] && continue
  {
    echo "# Claude Code session $sid"
    echo
    echo "Project \`$(basename "$(dirname "$f")")\`, started $first (UTC), exported $(date -u +%FT%TZ)."
    echo "User and assistant messages in order; tool calls as one line each, outputs omitted. Source: \`$f\`."
    echo
    jq -r "$JQ" "$f" 2>/dev/null
  } > "$dst.tmp" && mv "$dst.tmp" "$dst"
done

{
  echo "# Exported Claude Code sessions (newest first)"
  echo
  echo "Generated by scripts/export_context.sh on every snapshot. Read the newest one first when picking up work."
  echo
  for m in $(ls -1r "$OUT"/*.md 2>/dev/null); do
    n=$(grep -c '^### ' "$m")
    last=$(grep '^### ' "$m" | tail -1 | cut -c5-9)
    echo "- [$(basename "$m")](chats/$(basename "$m")): $n messages, last at $last UTC"
  done
} > "$REPO/context/INDEX.md"
